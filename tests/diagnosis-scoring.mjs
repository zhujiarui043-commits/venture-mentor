import assert from 'node:assert/strict';
import {mkdtemp,readFile,writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath,pathToFileURL} from 'node:url';
import ts from 'typescript';
const root=fileURLToPath(new URL('../',import.meta.url)),temp=await mkdtemp(join(tmpdir(),'diagnosis-scoring-'));
try {
  const rules=JSON.parse(await readFile(join(root,'knowledge/rules.json'),'utf8'));
  await writeFile(join(temp,'knowledge-rules.mjs'),`export default ${JSON.stringify(rules)};`);
  for(const name of ['hypothesis-assessment','types','diagnosis-scoring','knowledge','workflow','structured','materials','apply-proposal','hypothesis','proposal-changes','competition-workspace']) {
    const source=await readFile(join(root,`lib/${name}.ts`),'utf8');
    const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText
      .replace(/from "\.\/([a-z-]+)"/gu,'from "./$1.mjs"').replaceAll('from "@/knowledge/rules.json"','from "./knowledge-rules.mjs"');
    await writeFile(join(temp,`${name}.mjs`),compiled);
  }
  const get=name=>import(pathToFileURL(join(temp,`${name}.mjs`)));
  const {emptyProject,isDiagnosisScore,diagnosisNames}=await get('types');
  const {groundDiagnosisScore}=await get('diagnosis-scoring');
  const {selectKnowledge}=await get('knowledge');
  const {missingRequiredStructure}=await get('structured');
  const {bindMaterialSources}=await get('materials');
  const {applyProposal}=await get('apply-proposal');
  const state=emptyProject('score-tests');state.fields={audience:'备考大学生',solution:'学习助手'};
  const now='2026-10-10T14:00:00Z',earlier='2026-10-10T13:00:00Z';
  const base={name:diagnosisNames[0],attention:'需要关注',priority:'高',judgment:'目标用户基本明确',sourceRefs:['audience'],hypothesisRefs:[],limitations:'尚未完成访谈',riskImpact:'影响招募',nextStep:'访谈',score:2,scoreReason:'已明确使用情境，尚缺真实材料',scoreConfidence:'低',scoreTriggerRefs:[]};
  const score=(d,project=state,fields={},references='')=>groundDiagnosisScore(d,project,fields,references,'current-message',now);
  for(const valid of [0,1,2,3,4])assert.ok(isDiagnosisScore(valid));
  for(const invalid of [-1,5,1.5,NaN,'3',null,undefined])assert.equal(isDiagnosisScore(invalid),false);
  const noSource=score({...base,score:4,sourceRefs:['invented-source'],hypothesisRefs:['H99']});
  assert.equal(noSource.score,0);assert.equal(noSource.attention,'信息待补充');assert.equal(noSource.scoreConfidence,'低');
  assert.match(noSource.scoreReason,/暂无法判断/u);assert.deepEqual(noSource.sourceRefs,[]);
  const unverified=score({...base,score:4});assert.equal(unverified.score,2);assert.match(unverified.scoreReason,/缺少可追溯/u);
  state.messages=[{id:"U01",role:"user",content:"若能帮助我整理访谈，我每月愿意支付30元。",at:now}];
  assert.equal(score({...base,score:3,sourceRefs:["U01"]}).score,3);
  assert.equal(score({...base,score:4,sourceRefs:["U01"]}).score,3);
  state.materials=[{id:'M01',content:'真实用户访谈原文与行为记录',at:now}];
  for(const value of [0,1,2,3,4])assert.equal(score({...base,score:value,sourceRefs:['M01']}).score,value);
  const current=score({...base,score:3,sourceRefs:['当前材料'],scoreTriggerRefs:['当前材料']},state,{},'访谈材料');
  assert.equal(current.score,3);assert.deepEqual(current.scoreTriggerRefs,['当前材料']);
  const prior={...base,score:2,scoreUpdatedAt:earlier};
  state.artifacts=[{id:'old-score',section:'diagnosis',title:'旧版诊断',content:'旧版',version:1,createdAt:earlier,sources:[],limitations:'',nextStep:'',diagnosis:{summary:'旧版',keyRisk:'',firstQuestion:'',dimensions:[prior]}}];
  const withoutTrigger=score({...base,score:4,sourceRefs:['M01'],scoreTriggerRefs:['invented-source']});
  assert.equal(withoutTrigger.score,2);assert.equal(withoutTrigger.scoreUpdatedAt,earlier);assert.match(withoutTrigger.limitations,/保留上次评分/u);
  const withTrigger=score({...base,score:4,sourceRefs:['M01'],scoreTriggerRefs:['M01']});
  assert.equal(withTrigger.score,4);assert.equal(withTrigger.scoreUpdatedAt,now);assert.deepEqual(withTrigger.scoreTriggerRefs,['M01']);
  const unchangedWithNewEvidence=score({...base,score:2,sourceRefs:['M01'],scoreTriggerRefs:['M01']});
  assert.equal(unchangedWithNewEvidence.scoreUpdatedAt,now);
  state.fieldMeta.audience={updatedAt:earlier};
  assert.equal(score({...base,score:1,scoreTriggerRefs:['audience']},state,{audience:state.fields.audience}).score,2);
  assert.equal(score({...base,score:1,scoreTriggerRefs:['audience']},state,{audience:'用户明确修改后的群体'}).score,1);
  const learned=selectKnowledge('diagnosis','生成八维诊断',state).text;
  for(const chunk of rules.KB04S)assert.ok(learned.includes(chunk.text),`评分规则被截断：${chunk.title}`);
  assert.match(learned,/不取平均分/u);assert.match(learned,/真实付款/u);assert.match(learned,/信息待补充/u);
  const validArtifact={diagnosis:{dimensions:diagnosisNames.map(name=>({...base,name}))}};
  assert.equal(missingRequiredStructure('diagnosis','diagnosis','生成八维诊断',validArtifact),null);
  for(const invalid of [undefined,-1,5,1.5])assert.ok(missingRequiredStructure('diagnosis','diagnosis','生成八维诊断',{diagnosis:{dimensions:diagnosisNames.map(name=>({...base,name,score:invalid}))}}));
  assert.ok(missingRequiredStructure('diagnosis','diagnosis','生成八维诊断',{diagnosis:{dimensions:diagnosisNames.map(name=>({...base,name,scoreReason:' '}))}}));
  const proposal={id:'new-score',reply:'已生成',fields:{},fieldStatuses:{},fieldMeta:{},fieldRemovals:[],artifact:{section:'diagnosis',title:'新版诊断',content:'新版',limitations:'',nextStep:'',sources:[],diagnosis:{summary:'新版',keyRisk:'',firstQuestion:'',dimensions:[withTrigger]}},hypothesis:null,evidence:[],createdAt:now};
  const artifact=applyProposal(state,proposal);
  assert.equal(state.artifacts[0].diagnosis.dimensions[0].score,2);
  assert.equal(artifact.version,2);assert.equal(artifact.diagnosis.changes[0].previousScore,2);assert.equal(artifact.diagnosis.changes[0].currentScore,4);
  assert.deepEqual(artifact.diagnosis.changes[0].triggerRefs,['M01']);
  const bound=structuredClone(proposal);bound.artifact.diagnosis.dimensions=[current];
  bindMaterialSources(bound,state.materials,'current-message');
  assert.deepEqual(bound.artifact.diagnosis.dimensions[0].scoreTriggerRefs,['M01']);
  assert.deepEqual(bound.artifact.diagnosis.dimensions[0].sourceRefs,['M01']);
  const legacy=structuredClone(state);delete legacy.artifacts[0].diagnosis.dimensions[0].score;
  assert.equal(isDiagnosisScore(legacy.artifacts[0].diagnosis.dimensions[0].score),false);
  console.log('八维评分检查通过：完整知识规则、0–4整数校验、无信息0分、材料门槛、触发来源、无新依据保留评分、变化版本和旧记录未评分。');
} finally {await rm(temp,{recursive:true,force:true});}
