"""Split Adobe's Source Han Sans CN variable font for lazy web loading.

Requires fonttools[woff]. Pass the original WOFF2 and the repository root.
Glyph shapes are preserved. Derived subsets use the Qidian Han Sans name
to respect Adobe's reserved font name in the SIL Open Font License.
"""
import copy
import multiprocessing
from concurrent.futures import ProcessPoolExecutor
import pathlib
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

source, root = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
font = TTFont(source)
codepoints = set(font.getBestCmap())
# The UI face also covers Latin, digits and punctuation. All remaining glyphs
# are split by Unicode block; user-entered Chinese loads only needed blocks.
ui = set(range(0x20, 0x300)) | set(range(0x2000, 0x2070)) | set(range(0x3000, 0x3040)) | set(range(0xff00, 0xfff0))
for folder in ["app", "components", "lib"]:
    for path in (root / folder).rglob("*.tsx" if folder == "components" else "*.ts*"):
        ui.update(ord(char) for char in path.read_text() if ord(char) > 127)
ui &= codepoints
groups = [("ui", ui)]
rest = sorted(codepoints - ui)
for start in sorted(set(cp // 512 * 512 for cp in rest if cp < 0x10000)):
    groups.append((f"u{start:05x}", {cp for cp in rest if start <= cp < start + 512}))
supplementary = {cp for cp in rest if cp >= 0x10000}
if supplementary:
    groups.append(("supplementary", supplementary))

out = root / "public" / "fonts"
def render_face(group):
    name, points = group
    filename = f"source-han-{name}.woff2"
    if "--reuse" in sys.argv[3:] and (out / filename).exists():
        face = TTFont(out / filename)
    else:
        face = copy.deepcopy(font)
        options = subset.Options()
        options.flavor = "woff2"
        options.recalc_timestamp = False
        options.hinting = False
        options.layout_features = ["ccmp", "locl", "kern"]
        sub = subset.Subsetter(options=options)
        sub.populate(unicodes=points)
        sub.subset(face)
    for record in list(face["name"].names):
        if record.nameID in {1, 3, 4, 6, 16, 18, 21, 25} or record.nameID > 255:
            value = record.toUnicode().replace("SourceHanSansCN", "QidianHanSans").replace("Source Han Sans CN", "Qidian Han Sans")
            face["name"].setName(value, record.nameID, record.platformID, record.platEncID, record.langID)
    face.flavor = "woff2"
    filename = f"source-han-{name}.woff2"
    face.save(out / filename)
    ranges = []
    ordered = sorted(points)
    a = b = ordered[0]
    for cp in ordered[1:]:
        if cp == b + 1:
            b = cp
        else:
            ranges.append(f"U+{a:X}" + (f"-{b:X}" if b != a else ""))
            a = b = cp
    ranges.append(f"U+{a:X}" + (f"-{b:X}" if b != a else ""))
    rule = '@font-face{font-family:"Qidian Han Sans";font-style:normal;font-weight:250 900;font-display:swap;src:url("/fonts/' + filename + '") format("woff2");unicode-range:' + ','.join(ranges) + ';}'
    print(filename, (out / filename).stat().st_size, flush=True)
    return rule
with ProcessPoolExecutor(max_workers=4, mp_context=multiprocessing.get_context("fork")) as pool:
    rules = list(pool.map(render_face, groups))
(root / "app" / "source-han.css").write_text("/* Adobe Source Han Sans 2.005, SIL OFL 1.1. Generated by scripts/subset-source-han.py. */\n" + "\n".join(rules) + "\n")
